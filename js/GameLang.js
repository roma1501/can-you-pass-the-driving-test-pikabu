    line(key, params) {
        const set = this.lines[this.code()] || this.lines.ru;
        const list = set[key] || this.lines.ru[key];
        if (!list || !list.length) return '';
        let pick = list[Math.floor(Math.random() * list.length)];
        if (list.length > 1 && pick === this._last[key]) pick = list[(list.indexOf(pick) + 1) % list.length];
        this._last[key] = pick;
        return pick.replace(/\{(\w+)\}/g, (_, k) => (params && params[k] !== undefined ? String(params[k]) : ''));
    },
